import 'dart:convert';

import 'package:filmku/models/film.dart';
import 'package:filmku/models/series.dart';
import 'package:filmku/state/library.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';

// Bentuk respons GET /api/episodes dari backend filmku.
const _response = '''
{
  "series": {
    "slug": "FourStarPlayhouse-48Episodes",
    "title": "Four Star Playhouse 48 episodes",
    "year": 1952,
    "description": "Antologi drama.",
    "poster": "https://archive.org/services/img/FourStarPlayhouse-48Episodes",
    "downloads": 52000
  },
  "episodes": [
    {
      "season": 1, "episode": 1,
      "title": "Four star playhouse -S01E01 - My wife Geraldine",
      "duration": 1565,
      "thumbnail": "https://archive.org/download/x/thumb.jpg",
      "stream_url": "https://archive.org/download/x/ep1.mp4",
      "subtitle_url": "https://archive.org/download/x/ep1.autogenerated.vtt"
    },
    {
      "season": null, "episode": 3, "title": "Bonus 3", "duration": null,
      "thumbnail": null, "stream_url": "https://archive.org/download/x/b3.mp4", "subtitle_url": null
    },
    {
      "season": null, "episode": null, "title": "Behind the scenes", "duration": null,
      "thumbnail": null, "stream_url": null, "subtitle_url": null
    }
  ]
}
''';

void main() {
  final data = SeriesEpisodes.fromJson(jsonDecode(_response) as Map<String, dynamic>);
  final series = data.series;

  test('respons backend terbaca', () {
    expect(series.slug, 'FourStarPlayhouse-48Episodes');
    expect(series.year, 1952);
    expect(data.episodes, hasLength(3));
    expect(data.episodes.map((e) => e.label), ['S1 · E1', 'Episode 3', '']);
  });

  test('episode menjadi Film yang bisa diputar dan disimpan', () {
    final film = data.episodes[0].toFilm(series);
    expect(film.id, 'ep:FourStarPlayhouse-48Episodes/Four star playhouse -S01E01 - My wife Geraldine');
    expect(film.duration, '27 mnt'); // 1565 detik dibulatkan ke atas
    expect(film.posterUrl, 'https://archive.org/download/x/thumb.jpg');
    expect(film.videoUrl, 'https://archive.org/download/x/ep1.mp4');
    expect(film.subtitleUrl, 'https://archive.org/download/x/ep1.autogenerated.vtt');
    expect(film.playable, isTrue);
    expect(film.isRemote, isTrue);

    final restored = Film.fromJson(film.toJson());
    expect(restored.seriesSlug, 'FourStarPlayhouse-48Episodes');
    expect(restored.isRemote, isTrue);
  });

  test('episode tanpa thumbnail atau video', () {
    final film = data.episodes[2].toFilm(series);
    expect(film.posterUrl, series.poster);
    expect(film.duration, '');
    expect(film.playable, isFalse);
  });

  test('episode yang diputar masuk riwayat dan datanya ikut tersimpan', () async {
    SharedPreferences.setMockInitialValues({});
    await Library.instance.load();
    final film = data.episodes[0].toFilm(series);

    Library.instance.remember(film);
    Library.instance.saveProgress(film.id, const Duration(minutes: 5), const Duration(minutes: 26));

    expect(Library.instance.historyFilms.first.id, film.id);
    expect(Library.instance.progress(film.id), closeTo(5 / 26, 0.01));
    final prefs = await SharedPreferences.getInstance();
    expect(prefs.getString('remote_films'), contains(film.id));
  });
}
