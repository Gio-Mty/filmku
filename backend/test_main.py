class Base64Test(unittest.TestCase):
    def test_padding_ditambahkan_otomatis(self):
        encoded = base64.b64encode(b'{"a":1}').decode().rstrip("=")
        self.assertEqual(b64decode_padded(encoded), b'{"a":1}')

    def test_url_safe_standar_dan_spasi(self):
        raw = bytes([0xFB, 0xFF, 0xBF, 0x00])  # standar: "+/+/AA==", URL-safe: "-_-_AA=="
        self.assertEqual(b64decode_padded("+/+/AA"), raw)
        self.assertEqual(b64decode_padded("-_-_AA"), raw)
        self.assertEqual(b64decode_padded(" -_-_\nAA "), raw)

    def test_atribut_json_biasa_atau_base64(self):
        data = [{"title": "Ep 1"}]
        self.assertEqual(decode_hidden_attr(json.dumps(data)), data)
        encoded = base64.b64encode(json.dumps(data).encode()).decode().rstrip("=")
        self.assertEqual(decode_hidden_attr(encoded), data)


